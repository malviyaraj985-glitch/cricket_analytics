export function calculatePlayerImpactScore(p) {
  if (!p) return 80;
  
  const form = p.recent_form_score || 85;
  
  if (p.role === "Batter") {
    const avgScore = Math.min((p.batting_average || 35) / 55, 1.0) * 45;
    const srScore = Math.min((p.strike_rate || 85) / 115, 1.0) * 35;
    const formScore = (form / 100) * 20;
    return Math.min(99, Math.max(60, Math.round(avgScore + srScore + formScore)));
  }
  
  if (p.role === "Bowler") {
    const wktScore = Math.min((p.wickets || 50) / 180, 1.0) * 35;
    const avgScore = Math.max(0, (40 - (p.bowling_average || 30)) / 18) * 25;
    const econScore = Math.max(0, (6.5 - (p.economy || 5.2)) / 2.2) * 20;
    const formScore = (form / 100) * 20;
    return Math.min(99, Math.max(60, Math.round(wktScore + avgScore + econScore + formScore)));
  }
  
  if (p.role === "All-Rounder") {
    const batPart = (Math.min((p.batting_average || 28) / 45, 1.0) * 20) + (Math.min((p.strike_rate || 85) / 110, 1.0) * 15);
    const bowlPart = (Math.min((p.wickets || 50) / 150, 1.0) * 25) + (Math.max(0, (6.2 - (p.economy || 5.2)) / 1.8) * 20);
    const formScore = (form / 100) * 20;
    return Math.min(99, Math.max(60, Math.round(batPart + bowlPart + formScore)));
  }
  
  if (p.role === "Wicket-Keeper") {
    const batScore = (Math.min((p.batting_average || 35) / 50, 1.0) * 40) + (Math.min((p.strike_rate || 85) / 105, 1.0) * 20);
    const disScore = Math.min((p.dismissals || 50) / 150, 1.0) * 20;
    const formScore = (form / 100) * 20;
    return Math.min(99, Math.max(60, Math.round(batScore + disScore + formScore)));
  }
  
  return Math.round(form);
}
